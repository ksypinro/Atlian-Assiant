"""JecProvisioner (DM-19): config, service unit, binary check and the Automation 'Run script using Jira Edge Connector' template (EV section 25)."""
from __future__ import annotations

import re
from collections.abc import Callable, Mapping
from datetime import timedelta
from pathlib import Path
from typing import ClassVar

from ...core.errors import InvalidRequestError
from ...policy import ConfirmationHandler
from ..automation import AutomationAction, AutomationRuleTemplate
from .base import ProvisioningPlan, ProvisioningStep, ProvisionMode, VerificationReport, confirm_plan, pick_mode

MIN_JEC_VERSION = "1.0.0"          # minimum supported version: UNVERIFIED (VER-02); override with min_version


def _version_tuple(text: str) -> tuple[int, ...]:
    m = re.search(r"(\d+(?:\.\d+)+)", text)
    return tuple(int(x) for x in m.group(1).split(".")) if m else ()


def jec_config_yaml(*, app_name: str, base_url: str, api_key_ref: str, handler: str, python: str = "python", poll_ms: int = 1000, visibility: int = 30, max_messages: int = 10) -> str:
    """``jec-config.yaml``: the API key is a secret REFERENCE (an env var), never the key itself."""
    return f"""# generated by atlian-assiant (DM-19): do not put the API key in this file
appName: {app_name}
apiKey: ${{{api_key_ref}}}
baseUrl: {base_url}
actionMappings:
  atlassian-events:
    filepath: {python}
    sourceType: local
    args: ["-m", "atlian_assiant.events.jec", "--handler", "{handler}"]
pollerConf:
  pollingWaitIntervalInMillis: {poll_ms}
  visibilityTimeoutInSeconds: {visibility}
  maxNumberOfMessages: {max_messages}
"""


def systemd_unit(binary: str, config: Path, api_key_ref: str) -> str:
    return f"""[Unit]
Description=Jira Edge Connector (atlian-assiant handler)
After=network-online.target

[Service]
Type=simple
EnvironmentFile=/etc/jec/{api_key_ref}.env
ExecStart={binary} --config {config}
Restart=on-failure
User=jec
NoNewPrivileges=true

[Install]
WantedBy=multi-user.target
"""


class JecProvisioner:
    method_ids: ClassVar[frozenset[str]] = frozenset({"DM-19"})
    modes: ClassVar[frozenset[ProvisionMode]] = frozenset({ProvisionMode.GUIDED, ProvisionMode.API})

    def __init__(self, *, directory: Path, base_url: str, handler: str, app_name: str = "atlassian-events", api_key_ref: str = "JEC_API_KEY", binary: str = "jec",
                 entitlement_confirmed: bool = False, run: Callable[[list[str]], str] | None = None, min_version: str = MIN_JEC_VERSION, probe: object = None) -> None:
        self.directory, self.base_url, self.handler, self.app_name, self.key_ref, self.binary = directory, base_url, handler, app_name, api_key_ref, binary
        self.entitled, self._run, self.min_version, self._probe = entitlement_confirmed, run, min_version, probe

    def check_binary(self) -> str:
        if self._run is None:
            raise InvalidRequestError("cannot check the JEC binary", hint="Pass run=<callable executing argv and returning stdout> or verify `jec --version` by hand.", operation="events.provision")
        out = self._run([self.binary, "--version"])
        if _version_tuple(out) < _version_tuple(self.min_version):
            raise InvalidRequestError(f"JEC version {out.strip()!r} is older than {self.min_version}", hint="Upgrade the Jira Edge Connector binary.", operation="events.provision")
        return out.strip()

    def template(self) -> AutomationRuleTemplate:
        return AutomationRuleTemplate(name="Run script using Jira Edge Connector", product="jira", trigger="issue_created", action=AutomationAction.JEC,
                                      action_config={"app": self.app_name, "action_mapping": "atlassian-events"})

    async def plan(self, *, mode: ProvisionMode | None = None) -> ProvisioningPlan:
        chosen = pick_mode(mode, self.modes, (ProvisionMode.GUIDED,))
        warnings = ["JEC requires JSM Premium or Enterprise (EV section 25)", "the JEC script argument convention is unverified (VER-02): the default parser is tolerant, adapt it if needed"]
        if not self.entitled:
            warnings.append("an admin must confirm the JSM Premium/Enterprise entitlement before this can be applied")
        steps = tuple(ProvisioningStep(s, chosen, True, True) for s in (f"write jec-config.yaml and the service unit to {self.directory}", "check the JEC binary version",
                                                                         "create the 'Run script using Jira Edge Connector' Automation rule"))
        return ProvisioningPlan("DM-19", steps, {"mode": chosen.value, "directory": str(self.directory)}, tuple(warnings))

    async def apply(self, plan: ProvisioningPlan, *, confirm: ConfirmationHandler) -> Mapping[str, str]:
        await confirm_plan(plan, confirm, operation_id="webhook.jira.dynamic.register", target=self.app_name)
        if not self.entitled:
            raise InvalidRequestError("the JSM Premium/Enterprise entitlement is not confirmed", hint="Ask an admin to confirm it, then pass entitlement_confirmed=True.",
                                      operation="events.provision")
        version = self.check_binary() if self._run is not None else "unchecked"
        self.directory.mkdir(parents=True, exist_ok=True)
        config = self.directory / "jec-config.yaml"
        config.write_text(jec_config_yaml(app_name=self.app_name, base_url=self.base_url, api_key_ref=self.key_ref, handler=self.handler), encoding="utf-8")
        unit = self.directory / "jec.service"
        unit.write_text(systemd_unit(self.binary, config, self.key_ref), encoding="utf-8")
        return {**plan.outputs, "config": str(config), "service_unit": str(unit), "binary_version": version, "automation_template": self.template().name}

    async def verify(self, *, timeout: timedelta = timedelta(minutes=5)) -> VerificationReport:
        if self._probe is None:
            return VerificationReport("DM-19", False, None, "no end-to-end probe configured: pass probe=<awaitable returning a VerificationReport>")
        report: VerificationReport = await self._probe(timeout)  # type: ignore[operator]
        return report

    async def teardown(self, *, confirm: ConfirmationHandler) -> None:
        plan = ProvisioningPlan("DM-19", (ProvisioningStep("Remove the generated JEC config and service unit", ProvisionMode.GUIDED, False, True),), {})
        await confirm_plan(plan, confirm, operation_id="webhook.jira.dynamic.delete", target=self.app_name)
        for name in ("jec-config.yaml", "jec.service"):
            (self.directory / name).unlink(missing_ok=True)
