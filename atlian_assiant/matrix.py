def cell(backend: BackendKind | str, slug: str) -> str | None:
    """``"full"``, ``"partial"`` or ``None`` for one matrix cell."""
    return CELLS.get(BackendKind(backend).value, {}).get(slug)


def row_ops(slug: str) -> tuple[str, ...]:
    return ROW_OPS[slug]


def declared_operations(backend: BackendKind | str, partial: dict[str, tuple[str, ...]] | None = None,
                       overrides: dict[str, tuple[str, ...]] | None = None) -> frozenset[str]:
    """Operations a backend claims: the ops of its ``full`` rows (or the backend's ``overrides[slug]`` where a row means something else there),
    plus the listed subset of each ``partial`` row (``partial[slug]``)."""
    key = BackendKind(backend).value
    out: set[str] = set()
    for slug, kind in CELLS.get(key, {}).items():
        out.update((overrides or {}).get(slug, ROW_OPS[slug]) if kind == "full" else (partial or {}).get(slug, ()))
    return frozenset(out)
