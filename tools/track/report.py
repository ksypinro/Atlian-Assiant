"""Generate TRACKING.md (deterministic: no wall-clock values)."""
from __future__ import annotations

from collections import Counter, defaultdict

from .engine import SATISFIED, World
from .model import PHASES, ROOT, Status, TaskType
from .seed_design import hints

ICON = {Status.DONE: "✅", Status.IN_REVIEW: "🔍", Status.CLAIMED: "🔧", Status.CHANGES_REQUESTED: "↩️",
        Status.BLOCKED: "⛔", Status.TODO: "⬜", Status.WONT_DO: "🚫"}
NEXT_COLS = [Status.DONE, Status.IN_REVIEW, Status.CLAIMED, Status.CHANGES_REQUESTED, Status.BLOCKED, Status.TODO]


def pct(n: int, d: int) -> str:
    return f"{(100 * n // d) if d else 100}%"


def render(w: World) -> str:
    h = hints(w.store)
    tasks = [t for t in w.tasks.values()]
    real = [t for t in tasks if t.type is not TaskType.GATE]
    st = lambda t: w.status(t.id)  # noqa: E731
    out: list[str] = ["<!-- GENERATED by `python -m tools.track report` - DO NOT EDIT -->", "# Implementation tracking", ""]
    total_done = sum(1 for t in real if st(t) in SATISFIED)
    out += [f"**{total_done}/{len(real)} tasks done ({pct(total_done, len(real))})** · "
            f"{sum(1 for t in real if st(t) is Status.IN_REVIEW)} in review · "
            f"{sum(1 for t in real if st(t) is Status.BLOCKED)} blocked · "
            f"{len(w.ready_tasks())} ready for agents", ""]

    # 1 gate board
    out += ["## 1. Gate board", "", "| Phase | Name | Tasks | Done | Machine checks | Human items | Gate |", "|---|---|---|---|---|---|---|"]
    for p in PHASES:
        ph, rep = w.phases[p], w.gate_report(p)
        g = w.store.load_gate(p)
        gate = f"✅ signed by {g['by']} ({g['at'][:10]})" if g and g.get("signed") else ("🟡 ready to sign" if rep["all_done"] and rep["previous_signed"] else "⬜ open")
        out.append(f"| {p} | {ph.name} | {rep['total']} | {rep['done']} ({pct(rep['done'], rep['total'])}) | {len(ph.machine_checks)} | {len(ph.human_items)} | {gate} |")
    out += ["", "<details><summary>Exit criteria</summary>", ""]
    for p in PHASES:
        ph = w.phases[p]
        out.append(f"- **{p}** - {ph.exit_criteria}")
        out += [f"  - machine: `{c}`" for c in ph.machine_checks] + [f"  - human: {x}" for x in ph.human_items]
    out += ["", "</details>", ""]

    # 2 needs human
    out += ["## 2. Needs a human now", ""]
    review = [t for t in tasks if st(t) is Status.IN_REVIEW]
    out += [f"**Review queue ({len(review)})**", ""]
    for t in sorted(review, key=lambda t: (w.states[t.id].history[-1].at if w.states[t.id].history else "", t.id)):
        s = w.states[t.id]
        out.append(f"- `{t.id}` {t.title} - evidence: {s.evidence}")
    if not review:
        out.append("_empty_")
    blocked = [t for t in tasks if st(t) is Status.BLOCKED]
    out += ["", f"**Blocked ({len(blocked)})**", ""]
    by_need = defaultdict(list)
    for t in blocked:
        by_need[w.states[t.id].blocked.needs if w.states[t.id].blocked else "decision"].append(t)
    for need, ts in sorted(by_need.items()):
        out.append(f"- needs **{need}**: " + "; ".join(f"`{t.id}` ({w.states[t.id].blocked.reason if w.states[t.id].blocked else ''})" for t in ts))
    if not blocked:
        out.append("_none_")
    hum = [t for t in tasks if t.human_only and t.type is not TaskType.GATE and st(t) not in SATISFIED and w.phases and t.phase == PHASES[min(w.max_active_phase(), len(PHASES) - 1)]]
    gated = [t for t in tasks if t.needs != "none" and st(t) not in SATISFIED and t.needs not in w.environment()]
    out += ["", f"**Human-only tasks in the current window:** {len(hum)} · **tasks waiting on missing environment (credentials/sandbox/decision):** {len(gated)}", ""]
    dcrs = [t for t in tasks if t.type is TaskType.DCR and st(t) not in SATISFIED]
    out += [f"**Pending design-change requests:** {len(dcrs)}" + ("".join(f"\n- `{t.id}` {t.title}" for t in dcrs)), ""]

    # 3 workstream x phase
    out += ["## 3. Workstream × phase (done/total)", "", "| Workstream | " + " | ".join(PHASES) + " | Total |", "|---|" + "---|" * (len(PHASES) + 1)]
    for ws in w.store.load_workstreams():
        cells, tot_d, tot = [], 0, 0
        for p in PHASES:
            ts = [t for t in real if t.workstream == ws and t.phase == p]
            d = sum(1 for t in ts if st(t) in SATISFIED)
            cells.append(f"{d}/{len(ts)}" if ts else "·")
            tot_d, tot = tot_d + d, tot + len(ts)
        if tot:
            out.append(f"| {ws} | " + " | ".join(cells) + f" | {tot_d}/{tot} |")
    out.append("")

    # 4 matrix
    out += ["## 4. Operation × backend matrix (design §11)", "", "Legend: ✅ done · 🔍 review · 🔧 active · ⛔ blocked · ⬜ todo · — not in design", ""]
    cols = list(h["matrix_columns"].values())
    names = {v: k for k, v in h["matrix_columns"].items()}
    out += ["| Operation | " + " | ".join(names[c] for c in cols) + " |", "|---|" + "---|" * len(cols)]
    mx = {t.id: t for t in tasks if t.id.startswith("MX.")}
    for label, spec in h["matrix_rows"].items():
        row = []
        for c in cols:
            t = mx.get(f"MX.{c}.{spec['slug']}")
            row.append(ICON[st(t)] if t else "—")
        out.append(f"| {label} | " + " | ".join(row) + " |")
    out += ["", "| Backend | Cells done | Skeleton |", "|---|---|---|"]
    for c in cols:
        ts = [t for t in mx.values() if t.id.startswith(f"MX.{c}.")]
        d = sum(1 for t in ts if st(t) in SATISFIED)
        be = w.tasks.get(f"BE.{c}")
        out.append(f"| {names[c]} | {d}/{len(ts)} ({pct(d, len(ts))}) | {ICON[st(be)] if be else '—'} |")
    out.append("")

    # 5 DM ledger
    out += ["## 5. Delivery-method ledger (DM-01…DM-49) and cross-cutting rules", "", "| Method | Provisioner | Consumer + verifier + test | Phase |", "|---|---|---|---|"]
    for n in range(1, 50):
        dm = f"DM-{n:02d}"
        p, c, g = w.tasks.get(f"{dm}.P"), w.tasks.get(f"{dm}.C"), w.tasks.get(dm)
        if not (p or c or g):
            continue
        title = (c or g or p).title.split(":", 1)[-1].strip()[:60]
        out.append(f"| {dm} {title} | {ICON[st(p)] if p else '—'} | {ICON[st(c)] if c else (ICON[st(g)] + ' guard' if g else '—')} | {(c or g or p).phase} |")
    cc = [t for t in tasks if t.id.startswith("CC-")]
    out += ["", "| Cross-cutting | " + " | ".join(t.id[3:] for t in cc) + " |", "|---|" + "---|" * len(cc), "| status | " + " | ".join(ICON[st(t)] for t in cc) + " |", ""]

    # 6 contracts & quality
    def line(title: str, pre: str) -> str:
        ts = [t for t in tasks if t.id.startswith(pre)]
        d = sum(1 for t in ts if st(t) in SATISFIED)
        return f"| {title} | {d}/{len(ts)} | {pct(d, len(ts))} |"
    out += ["## 6. Contracts and quality", "", "| Area | Done | % |", "|---|---|---|", line("Protocol contract suites", "PROTO."), line("Backends (skeleton + factory)", "BE."),
            line("Agent tools", "TOOL-"), line("Security controls (human-reviewed)", "SEC-"), line("Test layers", "QA."), line("Verify against live docs", "VER-"), ""]
    ver = [t for t in tasks if t.id.startswith("VER-") and st(t) not in SATISFIED]
    out += [f"Open verification items: {len(ver)} (" + ", ".join(t.id for t in ver[:30]) + (" …" if len(ver) > 30 else "") + ")", ""]

    # 7 regressions / critical path
    reg = [t for t in tasks if w.regressed(t.id)]
    out += ["## 7. Regressions and critical path", "", f"**Regressed (done but checks now fail): {len(reg)}**" + ("".join(f"\n- `{t.id}`" for t in reg)), ""]
    wt = w.weight()
    open_ = [t for t in real if st(t) not in SATISFIED]
    nxt = next((p for p in PHASES if not w.signed(p)), None)
    out.append(f"Critical path to gate **{nxt}** (open tasks with the most dependents):" if nxt else "All gates signed.")
    out.append("")
    cand = sorted((t for t in open_ if t.phase == nxt), key=lambda t: (-wt[t.id], t.id))[:12] if nxt else []
    out += ["| Task | Status | Dependents depth | Ready |", "|---|---|---|---|"]
    out += [f"| `{t.id}` {t.title[:70]} | {ICON[st(t)]} | {wt[t.id]} | {'yes' if w.is_ready(t) else 'no'} |" for t in cand]
    out += ["", "**Next ready tasks for agents:**", ""]
    out += [f"{i}. `{t.id}` ({t.phase}, {t.size}) {t.title}" for i, t in enumerate(w.ready_tasks()[:10], 1)] or ["_none_"]
    out.append("")

    # 8 agent activity
    out += ["## 8. Agent activity", "", "| Agent | Active | In review | Done |", "|---|---|---|---|"]
    agents: dict[str, Counter] = defaultdict(Counter)
    for s in w.states.values():
        for hst in s.history:
            if hst.event == "approved":
                pass
        if s.claimed_by:
            agents[s.claimed_by]["active"] += 1
        sub = [x.by for x in s.history if x.event == "submitted"]
        if sub and s.status is Status.IN_REVIEW:
            agents[sub[-1]]["review"] += 1
        if sub and s.status is Status.DONE:
            agents[sub[-1]]["done"] += 1
    for a, c in sorted(agents.items()):
        out.append(f"| {a} | {c['active']} | {c['review']} | {c['done']} |")
    if not agents:
        out.append("| _no activity yet_ | | | |")
    claimed = [(s.id, s.claimed_by, s.lease_expires) for s in w.states.values() if s.status is Status.CLAIMED]
    out += ["", "Active leases: " + (", ".join(f"`{i}` by {a} until {e}" for i, a, e in claimed) if claimed else "none"), ""]
    return "\n".join(out) + "\n"


def write(w: World) -> str:
    text = render(w)
    (ROOT / "TRACKING.md").write_text(text, encoding="utf-8")
    return text


def check(w: World) -> bool:
    p = ROOT / "TRACKING.md"
    return p.exists() and p.read_text(encoding="utf-8") == render(w)
