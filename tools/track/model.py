"""Data model and file store for the implementation tracker.

Definitions (what to do) and state (progress) live in separate files so that
regenerating tasks never overwrites progress. A task with no state file is `todo`.
"""
from __future__ import annotations

import re
from datetime import datetime, timezone
from enum import StrEnum
from pathlib import Path
from typing import Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field

ROOT = Path(__file__).resolve().parents[2]
TRACKING = ROOT / "tracking"
DEFS_AUTHORED = TRACKING / "definitions" / "authored"
DEFS_GENERATED = TRACKING / "definitions" / "generated"
STATE_DIR = TRACKING / "state"
GATES_DIR = TRACKING / "gates"
EVIDENCE_DIR = TRACKING / "evidence"
RESULTS_DIR = TRACKING / ".results"
DESIGN = ROOT / "atlassian_client_architecture_design.md"

PHASES = ["P0", "P1", "P2", "P3", "P4", "P4b", "P4c", "P5", "P6"]
ID_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._\-]*$")


class TaskType(StrEnum):
    BUILD = "build"
    TEST = "test"
    DOCS = "docs"
    RESEARCH = "research"
    SECURITY = "security"
    GATE = "gate"
    DCR = "dcr"


class Status(StrEnum):
    TODO = "todo"
    CLAIMED = "claimed"
    IN_REVIEW = "in_review"
    CHANGES_REQUESTED = "changes_requested"
    BLOCKED = "blocked"
    DONE = "done"
    WONT_DO = "wont_do"


Needs = Literal["none", "credentials", "sandbox", "decision"]


class Task(BaseModel):
    model_config = ConfigDict(extra="forbid")

    id: str
    title: str
    type: TaskType = TaskType.BUILD
    phase: str
    workstream: str
    design_refs: list[str] = Field(default_factory=list)
    research_refs: list[str] = Field(default_factory=list)
    depends_on: list[str] = Field(default_factory=list)
    deliverables: list[str] = Field(default_factory=list)
    acceptance: list[str] = Field(default_factory=list)
    checks: list[str] = Field(default_factory=list)
    size: Literal["S", "M"] = "M"
    human_only: bool = False
    needs: Needs = "none"
    source: str = "authored"  # authored | design:<table> | code:<catalog>


class HistoryEntry(BaseModel):
    at: str
    by: str
    event: str
    note: str = ""


class Review(BaseModel):
    by: str
    at: str
    decision: Literal["approved", "rejected"]
    notes: str = ""


class Blocked(BaseModel):
    reason: str
    needs: Needs = "decision"


class State(BaseModel):
    model_config = ConfigDict(extra="forbid")

    id: str
    status: Status = Status.TODO
    claimed_by: str | None = None
    lease_expires: str | None = None
    commits: list[str] = Field(default_factory=list)
    evidence: str | None = None
    review: Review | None = None
    blocked: Blocked | None = None
    history: list[HistoryEntry] = Field(default_factory=list)


class Phase(BaseModel):
    id: str
    name: str
    scope: str
    exit_criteria: str
    machine_checks: list[str] = Field(default_factory=list)
    human_items: list[str] = Field(default_factory=list)


def now() -> datetime:
    return datetime.now(timezone.utc).replace(microsecond=0)


def iso(dt: datetime) -> str:
    return dt.isoformat().replace("+00:00", "Z")


def parse_iso(s: str) -> datetime:
    return datetime.fromisoformat(s.replace("Z", "+00:00"))


def phase_index(phase: str) -> int:
    return PHASES.index(phase)


def _dump(path: Path, data: dict, header: str = "") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100)
    path.write_text(header + body, encoding="utf-8")


def _safe(task_id: str) -> str:
    return task_id.replace("/", "_")


class Store:
    """Reads definitions/state; writes state, gates and generated definitions."""

    def __init__(self, root: Path | None = None) -> None:
        base = (root or ROOT) / "tracking"
        self.base = base
        self.authored = base / "definitions" / "authored"
        self.generated = base / "definitions" / "generated"
        self.state_dir = base / "state"
        self.gates_dir = base / "gates"
        self.evidence_dir = base / "evidence"
        self.defs = base / "definitions"

    # ---- definitions ----
    def load_tasks(self) -> dict[str, Task]:
        tasks: dict[str, Task] = {}
        for folder in (self.authored, self.generated):
            for p in sorted(folder.glob("*.yaml")):
                t = Task.model_validate(yaml.safe_load(p.read_text(encoding="utf-8")))
                if t.id in tasks:
                    raise ValueError(f"duplicate task id {t.id} ({p})")
                tasks[t.id] = t
        return tasks

    def write_generated(self, tasks: list[Task]) -> tuple[int, int]:
        """Replace generated definitions with `tasks`. Returns (written, removed)."""
        self.generated.mkdir(parents=True, exist_ok=True)
        keep = set()
        header = "# GENERATED by `track seed` - DO NOT EDIT (changes go through the design doc or a DCR)\n"
        for t in tasks:
            path = self.generated / f"{_safe(t.id)}.yaml"
            keep.add(path.name)
            _dump(path, t.model_dump(mode="json"), header)
        removed = 0
        for p in self.generated.glob("*.yaml"):
            if p.name not in keep:
                p.unlink()
                removed += 1
        return len(tasks), removed

    def load_phases(self) -> dict[str, Phase]:
        data = yaml.safe_load((self.defs / "phases.yaml").read_text(encoding="utf-8"))
        return {p["id"]: Phase.model_validate(p) for p in data["phases"]}

    def load_workstreams(self) -> dict[str, str]:
        data = yaml.safe_load((self.defs / "workstreams.yaml").read_text(encoding="utf-8"))
        return dict(data["workstreams"])

    # ---- state ----
    def load_state(self, task_id: str) -> State:
        p = self.state_dir / f"{_safe(task_id)}.yaml"
        if not p.exists():
            return State(id=task_id)
        return State.model_validate(yaml.safe_load(p.read_text(encoding="utf-8")))

    def load_all_states(self) -> dict[str, State]:
        out: dict[str, State] = {}
        for p in sorted(self.state_dir.glob("*.yaml")):
            s = State.model_validate(yaml.safe_load(p.read_text(encoding="utf-8")))
            out[s.id] = s
        return out

    def save_state(self, state: State) -> None:
        _dump(self.state_dir / f"{_safe(state.id)}.yaml", state.model_dump(mode="json", exclude_none=True))

    # ---- gates ----
    def load_gate(self, phase: str) -> dict | None:
        p = self.gates_dir / f"{phase}.yaml"
        return yaml.safe_load(p.read_text(encoding="utf-8")) if p.exists() else None

    def save_gate(self, phase: str, data: dict) -> None:
        _dump(self.gates_dir / f"{phase}.yaml", data)
