def _model_imports() -> str:
    """Explicit imports of every public model class (a star import would hide the jira / confluence ``Attachment`` clash). Confluence wins the bare name, jira is ``Jira*``."""
    import importlib

    import pydantic

    taken: set[str] = {"Attachment", "AttachmentContent"}
    lines = ["from atlian_assiant.models.confluence import Attachment, AttachmentContent\n"]
    for mod in ("common", "admin", "graph", "identity", "jira", "confluence", "jsm", "webhooks"):
        m = importlib.import_module(f"atlian_assiant.models.{mod}")
        names = sorted(n for n, o in vars(m).items() if isinstance(o, type) and issubclass(o, pydantic.BaseModel) and o.__module__ == m.__name__ and n not in taken and not n.startswith("_") and "[" not in n)
        taken |= set(names)
        if names:
            lines.append(f"from atlian_assiant.models.{mod} import {', '.join(names)}\n")
    return "".join(lines)


def render() -> str:
    from tools.docgen import build_fake_client

    client = build_fake_client()
    seen: dict[str, str] = {}
    order: list[str] = []
    attrs: list[tuple[str, str]] = []
    for attr, value in sorted(vars(client).items()):
        if attr.startswith("_") or attr in ("router", "config", "core", "build_report", "preset", "policy", "confirm"):
            continue
        if type(value).__name__ == "Unavailable":
            continue
        if getattr(value, "__namespace__", False) is True or hasattr(value, "_OPS") or attr == "tools":
            attrs.append((attr, _class_for(value, seen, order)))
    body = "".join("\n" + seen[n] for n in order)
    methods = ["    def describe(self) -> dict[str, Any]: ...\n", "    def help(self, name: str) -> str: ...\n", "    def health(self) -> dict[str, str]: ...\n",
               "    def whoami(self) -> Identity: ...\n"]
    tail = _CLIENT_TAIL.replace("    def close(self) -> None: ...", "".join(f"    {a}: {c}\n" for a, c in attrs) + "".join(methods) + "    def close(self) -> None: ...")
    return HEADER.replace("__MODEL_IMPORTS__", _model_imports()) + body + tail


def main(argv: list[str] | None = None) -> int:
    args = argv if argv is not None else sys.argv[1:]
    text = render()
    if "--write" in args:
        OUT.write_text(text, encoding="utf-8")
        print("wrote", OUT.relative_to(ROOT))
        return 0
    if "--check" in args:
        stale = not OUT.exists() or OUT.read_text(encoding="utf-8") != text
        print("stubs check:", "STALE (run `python -m tools.gen_stubs --write`)" if stale else "ok")
        return 1 if stale else 0
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
