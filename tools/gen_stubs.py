def _fmt(sig: inspect.Signature, *, drop_self: bool = False) -> str:
    parts: list[str] = []
    star_done = False
    for i, (name, p) in enumerate(sig.parameters.items()):
        if i == 0 and name == "self":
            parts.append("self")
            continue
        if p.kind is p.KEYWORD_ONLY and not star_done:
            parts.append("*")
            star_done = True
        if p.kind is p.VAR_POSITIONAL:
            star_done = True
        if p.kind is p.VAR_KEYWORD:
            text = f"**{name}"
        elif p.kind is p.VAR_POSITIONAL:
            text = f"*{name}"
        else:
            text = name
        ann = p.annotation if p.annotation is not inspect.Parameter.empty else "Any"
        text += f": {ann}"
        if p.default is not inspect.Parameter.empty:
            text += " = ..."
        parts.append(text)
    return ", ".join(parts)


def _ret(sig: inspect.Signature) -> str:
    ann = sig.return_annotation
    return "Any" if ann is inspect.Signature.empty else str(ann)


def _doc_line(fn: Any) -> str:
    doc = inspect.getdoc(fn) or ""
    first = doc.strip().splitlines()[0].replace('"', "'") if doc.strip() else ""
    return f'        """{first}"""\n' if first else ""


def _class_for(obj: Any, seen: dict[str, str], order: list[str]) -> str:
    cls = type(obj)
    name = cls.__name__
    if name in seen:
        return name
    seen[name] = ""                                                     # reserve (recursion guard)
    lines = [f"class {name}:\n"]
    doc = (inspect.getdoc(cls) or "").strip().splitlines()
    if doc:
        lines.append(f'    """{doc[0].replace(chr(34), chr(39))}"""\n')
    attr_lines: list[str] = []
    for attr, value in sorted(vars(obj).items()):
        if attr.startswith("_"):
            continue
        if getattr(value, "__namespace__", False) is True or (hasattr(value, "_OPS") and getattr(value, "__namespace__", True) is not False):
            attr_lines.append(f"    {attr}: {_class_for(value, seen, order)}\n")
    members: list[str] = []
    for attr, fn in inspect.getmembers(cls, predicate=lambda m: inspect.isfunction(m)):
        if attr.startswith("_"):
            continue
        sig = inspect.signature(fn)
        if inspect.isasyncgenfunction(fn):
            inner = _ret(sig)
            ret = f"Iterator[{inner[len('AsyncIterator['):-1]}]" if inner.startswith("AsyncIterator[") else "Iterator[Any]"
        else:
            ret = _ret(sig)
        members.append(f"    def {attr}({_fmt(sig)}) -> {ret}:\n{_doc_line(fn)}        ...\n")
    seen[name] = "".join(lines) + ("".join(attr_lines + members) or "    ...\n")
    order.append(name)
    return name


